// `path` is always the German path, e.g. '/posts/' or '/llms/'.
export function href(lang, path) {
  return lang === 'en' ? `/en${path}` : path;
}

// WordPress dates are local wall-clock times without a zone ("2026-02-24T12:45:20").
export function formatDate(localIso, lang) {
  return new Intl.DateTimeFormat(ui[lang].locale, {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
    timeZone: 'UTC',
  }).format(new Date(`${localIso}Z`));
}
